// Tests for adapters/s3c/integrate.mjs (plan 2026-10-21-m4-m7-plan.md §M6 exit criterion 5; M4-RUN.md open defect 4).
// A fixture company repo in a temp dir: a primary checkout on its main branch, an integration worktree on meta/m6, and
// order branches that add lessons. Its tools/company.mjs is a stand-in whose `registry` writes
// src/demos/index.generated.ts from every src/demos/<d>/<slug>/meta.json, sorted (as tools/registry.mjs does, in
// shape); the real company tool is protected and is run only through the adapter. Nothing outside the temp dir is touched.
import { test, after } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync, execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ADAPTER = path.join(HERE, "..", "integrate.mjs");
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), "s3c-integrate-"));
after(() => fs.rmSync(TMP, { recursive: true, force: true }));
const env0 = () => { const e = { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" }; delete e.NODE_TEST_CONTEXT; for (const k of Object.keys(e)) if (k.startsWith("GIT_CONFIG")) delete e[k]; return e; };
const git = (cwd, ...a) => execFileSync("git", ["-C", cwd, ...a], { encoding: "utf8", env: env0() }).trim();
const w = (root, rel, s) => { fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); fs.writeFileSync(path.join(root, rel), s); };
const REGISTRY = `import fs from "node:fs"; import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
if (process.argv[2] !== "registry") process.exit(2);
const d = path.join(root, "src/demos"), out = [];
for (const dom of fs.readdirSync(d).filter((x) => fs.statSync(path.join(d, x)).isDirectory()).sort()) for (const s of fs.readdirSync(path.join(d, dom)).sort()) if (fs.existsSync(path.join(d, dom, s, "meta.json"))) out.push(\`export * as \${s.replace(/-/g, "_")} from "./\${dom}/\${s}";\`);
const f = path.join(d, "index.generated.ts"), src = "// generated by tools/registry.mjs\\n" + out.join("\\n") + "\\n";
if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== src) { fs.writeFileSync(f, src); console.log("registry: regenerated 1 file(s)"); } else console.log("registry: up to date");
`;
const registryIn = (root) => execFileSync(process.execPath, ["tools/company.mjs", "registry"], { cwd: root, encoding: "utf8", env: env0() });

// the base: one lesson m-mid, a shared file, the registry; meta/m6 is its integration branch, in a linked worktree
const MAIN = path.join(TMP, "repo"), INT = path.join(TMP, "m6-int");
fs.mkdirSync(MAIN);
git(MAIN, "init", "-q", "-b", "main");
w(MAIN, "tools/company.mjs", REGISTRY);
w(MAIN, "src/demos/math/m-mid/meta.json", "{}\n");
w(MAIN, "src/shared.ts", "export const x = 1;\n");
registryIn(MAIN);
git(MAIN, "add", "-A"); git(MAIN, "commit", "-qm", "base");
git(MAIN, "branch", "meta/m6");
git(MAIN, "worktree", "add", "-q", INT, "meta/m6");
// an order branch from the base: add a lesson (and regenerate the registry, as new-demo does, unless told not to)
function order(name, slug, { registry = true, extra = null, deployMsg = false } = {}) {
  const wt = path.join(TMP, `wt-${name}`);
  git(MAIN, "worktree", "add", "-q", "-b", `meta/m6-${name}`, wt, "main");
  w(wt, `src/demos/math/${slug}/meta.json`, `{"slug":"${slug}"}\n`);
  if (registry) registryIn(wt);
  if (extra) extra(wt);
  git(wt, "add", "-A"); git(wt, "commit", "-qm", deployMsg ? `meta: O-9 ship ${slug} [deploy]` : `meta: build ${slug}`);
  return `meta/m6-${name}`;
}
const A = order("A", "a-one"), B = order("B", "b-two"), C = order("C", "c-three", { registry: false });
const D = order("D", "d-four", { extra: (wt) => w(wt, "src/shared.ts", "export const x = 4;\n") });
const E = order("E", "e-five", { deployMsg: true });
const F2 = order("F", "f-six", { extra: (wt) => w(wt, "src/shared.ts", "export const x = 6;\n") });
const integrate = (args, extraEnv = {}) => {
  const r = spawnSync(process.execPath, [ADAPTER, ...args], { encoding: "utf8", env: { ...env0(), ...extraEnv } });
  return { code: r.status, json: JSON.parse(r.stdout.trim().split("\n").at(-1)), stdout: r.stdout, stderr: r.stderr };
};
const merge = (from, extraEnv) => integrate([`--into=meta/m6`, `--from=${from}`, `--repo=${INT}`], extraEnv);
const registryFile = () => fs.readFileSync(path.join(INT, "src/demos/index.generated.ts"), "utf8");
const head = () => git(INT, "rev-parse", "HEAD");

test("a clean merge (--no-ff, the repo's own hooks run even under the kernel's git pins), then a registry-only conflict resolved by code", () => {
  // a post-merge hook in the shared hooks folder: it must run (the kernel's GIT_CONFIG pins, core.hooksPath=/dev/null, are not inherited)
  const hooks = path.join(MAIN, ".git", "hooks"); fs.mkdirSync(hooks, { recursive: true });
  fs.writeFileSync(path.join(hooks, "post-merge"), `#!/bin/sh\necho ran >> "${path.join(TMP, "hook-ran")}"\n`, { mode: 0o755 });
  const a = merge(A, { GIT_CONFIG_COUNT: "1", GIT_CONFIG_KEY_0: "core.hooksPath", GIT_CONFIG_VALUE_0: "/dev/null" });
  assert.equal(a.code, 0, a.stdout + a.stderr);
  assert.deepEqual([a.json.merged, a.json.upToDate, a.json.resolved, a.json.registry], [true, false, [], "up to date"]);
  assert.equal(git(INT, "log", "-1", "--format=%s"), "meta: merge meta/m6-A into meta/m6");
  assert.equal(git(INT, "rev-list", "--parents", "-n1", "HEAD").split(" ").length, 3, "--no-ff: a merge commit, never the order's own tip");
  assert.ok(fs.existsSync(path.join(TMP, "hook-ran")), "the repo's post-merge hook ran");
  fs.rmSync(path.join(hooks, "post-merge"));
  // B regenerated the registry from the base too: both branches changed its same lines
  const b = merge(B);
  assert.equal(b.code, 0, b.stdout + b.stderr);
  assert.deepEqual([b.json.merged, b.json.resolved, b.json.registry], [true, ["src/demos/index.generated.ts"], "up to date"]);
  assert.match(registryFile(), /a_one[\s\S]*b_two[\s\S]*m_mid/, "regenerated from every lesson in the tree");
  assert.equal(git(INT, "status", "--porcelain"), "");
  assert.equal(git(INT, "rev-list", "--parents", "-n1", "HEAD").split(" ").length, 3, "the merge was concluded, not a squash");
});

test("a clean textual merge that leaves the registry stale (M4): the registry is regenerated and committed", () => {
  const c = merge(C);
  assert.equal(c.code, 0, c.stdout);
  assert.deepEqual([c.json.merged, c.json.registry], [true, "committed"]);
  assert.match(registryFile(), /c_three/);
  assert.equal(git(INT, "log", "-1", "--format=%s"), "meta: registry regenerated after merging meta/m6-C");
  // a retry (already merged): no merge, the registry is checked again, nothing to commit
  const again = merge(C);
  assert.equal(again.code, 0);
  assert.deepEqual([again.json.merged, again.json.upToDate, again.json.registry], [false, true, "up to date"]);
});

test("a conflict outside the registry aborts the merge and parks (an ask, no agent hand-merges); a [deploy] commit is never merged", () => {
  assert.equal(merge(D).code, 0, "D changes the shared file first: clean");
  const before = head();
  const f = merge(F2);
  assert.equal(f.code, 1, f.stdout);
  assert.equal(f.json.route, "park"); assert.equal(f.json.park, true);
  assert.deepEqual(f.json.conflicts.sort(), ["src/demos/index.generated.ts", "src/shared.ts"].sort());
  assert.match(f.stdout, /^block conflict: merging meta\/m6-F into meta\/m6 conflicts in src\/shared\.ts \(and the generated registry\)/m);
  assert.equal(f.json.ask.kind, "decision");
  assert.equal(head(), before, "nothing merged");
  assert.equal(git(INT, "status", "--porcelain"), "", "the merge was aborted");
  const e = merge(E);
  assert.equal(e.code, 1); assert.equal(e.json.route, "park");
  assert.match(e.stdout, /names \[deploy\]/);
  assert.equal(head(), before);
});

test("refusals: not a meta/* branch, the main checkout or a primary one, another branch checked out, tracked changes, a merge of something else half done", () => {
  assert.equal(integrate(["--into=main", `--from=${A}`, `--repo=${INT}`]).code, 2);
  assert.match(integrate(["--into=meta/m6", `--from=${A}`, `--repo=${MAIN}`]).json.findings[0].message, /primary checkout/);
  assert.match(integrate(["--into=meta/m6", `--from=${A}`, "--repo=/home/user/system-3-company"]).json.findings[0].message, /main checkout|primary checkout/);
  assert.equal(integrate([`--from=${A}`, `--repo=${INT}`]).code, 2);
  assert.equal(integrate(["--into=meta/m6", "--from=--x", `--repo=${INT}`]).code, 2);
  const other = integrate(["--into=meta/m6-x", `--from=${A}`, `--repo=${INT}`]);
  assert.equal(other.code, 3); assert.match(other.json.findings[0].message, /is on meta\/m6, not meta\/m6-x/);
  assert.equal(merge("meta/no-such").code, 3);
  w(INT, "src/shared.ts", "dirty\n");
  const d = merge(B);
  assert.equal(d.code, 3); assert.match(d.json.findings[0].message, /uncommitted changes/);
  git(INT, "checkout", "--", "src/shared.ts");
  // an earlier attempt of the same branch left half done (a timeout mid-merge): aborted, then made again
  const H = order("H", "h-eight"), I = order("I", "i-nine");
  const half = (b) => spawnSync("git", ["-C", INT, "merge", "--no-ff", "--no-edit", b], { env: env0(), encoding: "utf8" });
  assert.notEqual(half(H).status, 0, "the registry conflicts: MERGE_HEAD is left");
  const other2 = merge(I);
  assert.equal(other2.code, 3); assert.match(other2.json.findings[0].message, /merge of .* in progress, not of meta\/m6-I/);
  const h = merge(H);
  assert.equal(h.code, 0, h.stdout);
  assert.match(h.stdout, /^advisory retry: an earlier merge of meta\/m6-H was left half done/m);
  assert.deepEqual(h.json.resolved, ["src/demos/index.generated.ts"]);
  assert.match(registryFile(), /h_eight/);
});
