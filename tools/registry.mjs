// Registry generator: meta.json files on disk -> src/demos/*.generated.ts (AMD-001 (c2) + rider R1, W-946).
// Ordinary surface (AMD-001): change it through normal engineering review (EDD-001). Run it with
// `npm run registry` (tools/company.mjs registry calls registryFiles and writes the map).
//
// Two files, one per side (company/engineering/notes/2026-10-15-w946-loaders-design.md section 2):
//   src/demos/index.generated.ts    every meta.json and `demos`. Server only (imports "server-only"): imported by src/lib/catalog.ts alone.
//   src/demos/loaders.generated.ts  one `import()` per Demo and `loaders`. Client: imported by DemoHost.tsx alone.
// tools/company.mjs `check` regenerates in memory, fails on drift and orphans, and judges invariants 1 to 6
// whatever this file does: every lesson imported from its own meta.json, exactly one loader per lesson keyed by
// its own slug, no status literal, no file holding both metas and loaders, no generated file importing another.
// So: never inline meta fields here, never filter by status, never re-export one generated file from another.

import fs from "node:fs";
import path from "node:path";

const HEAD = ["// GENERATED by `node tools/company.mjs registry`. Do not edit by hand.", "// Source of truth: src/demos/<domain>/<slug>/meta.json"];

/** Returns { "<repo-relative path>": "<file contents>" } for every generated file. */
export function registryFiles(demos) {
  const ok = demos.filter((d) => d.meta && fs.existsSync(path.join(d.dir, "Demo.tsx")));

  // `import "server-only"` makes a client importer fail `next build`, which CI runs (review C1 / F2).
  const idx = [...HEAD, "// Server only (src/lib/catalog.ts). Never import from a client module (W-946).", 'import "server-only";', 'import type { DemoMeta } from "@/kit/types";'];
  ok.forEach((d, i) => idx.push(`import m${i} from "./${d.domainDir}/${d.slugDir}/meta.json";`));
  idx.push("", `export const demos: DemoMeta[] = [${ok.map((_, i) => `m${i} as DemoMeta`).join(", ")}];`);

  const ld = [...HEAD, "// Client (src/components/DemoHost.tsx). No meta.json here (W-946).", 'import type { ComponentType } from "react";', "",
    "export const loaders: Record<string, () => Promise<{ default: ComponentType<{ slug: string }> }>> = {"];
  ok.forEach((d) => ld.push(`  ${JSON.stringify(d.meta.slug)}: () => import("./${d.domainDir}/${d.slugDir}/Demo"),`));
  ld.push("};");

  return { "src/demos/index.generated.ts": idx.join("\n") + "\n", "src/demos/loaders.generated.ts": ld.join("\n") + "\n" };
}
