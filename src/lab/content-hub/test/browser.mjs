// Run with: node src/lab/content-hub/test/browser.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { startPrototype } from '../server.mjs';
import { demoFiles } from '../fixtures.mjs';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'hub-browser-'));
const server = await startPrototype({ root });
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const errors = [], results = [];
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(server.hostOrigin);
  const frame = page.frameLocator('#preview');
  await frame.getByText('5 × 2 = 10').waitFor();
  await frame.locator('input').evaluate(input => { input.value = '10'; input.dispatchEvent(new Event('input')); });
  await frame.getByText('10 × 2 = 20').waitFor();
  assert.equal(await page.locator('#preview').evaluate(el => el.contentDocument === null), true);
  const beta = server.hub.publication('research', 'beta');
  const original = server.hub.jobs('research').find(j => j.demo === 'alpha');
  const changed = demoFiles('alpha', 4);
  await page.locator('#source').fill(changed['demos/alpha/index.ts']);
  await page.locator('#tests').fill(changed['demos/alpha/test.mjs']);
  await page.getByRole('button', { name: 'Save Git revision' }).click();
  await page.getByRole('status').filter({ hasText: '1 affected demo build(s) queued' }).waitFor();
  await page.getByRole('button', { name: 'Run queued builds' }).click();
  await page.getByRole('status').filter({ hasText: 'alpha: ready' }).waitFor({ timeout: 45000 });
  await page.getByRole('button', { name: 'Publish this build', exact: true }).click();
  await frame.getByText('5 × 4 = 20').waitFor();
  assert.deepEqual(server.hub.publication('research', 'beta'), beta);
  results.push({ check: 'edit → commit → scoped queue → tests/compiler → publish → browser artifact', pass: true });
  await page.locator('#source').fill('export const broken: number = "wrong";');
  await page.getByRole('button', { name: 'Save Git revision' }).click();
  await page.getByRole('status').filter({ hasText: 'queued' }).waitFor();
  await page.getByRole('button', { name: 'Run queued builds' }).click();
  await page.getByRole('status').filter({ hasText: 'alpha: failed' }).waitFor({ timeout: 45000 });
  await frame.getByText('5 × 4 = 20').waitFor();
  results.push({ check: 'compiler failure preserves running published demo', pass: true });
  await page.locator('.job').filter({ hasText: original.sha.slice(0, 10) }).getByRole('button').click();
  await frame.getByText('5 × 2 = 10').waitFor();
  results.push({ check: 'historical artifact rollback renders without compiling', pass: true });
  const state = await (await fetch(server.hostOrigin + '/api/state')).json();
  const publication = state.publications.find(p => p.demo === 'alpha');
  const manifest = server.hub.artifact('research', publication.artifact);
  const artifactUrl = server.assetOrigin + '/objects/research/' + publication.artifact + '/' + manifest.entry;
  const count = state.jobs.length;
  const artifact = await fetch(artifactUrl);
  assert.equal(artifact.status, 200); assert.match(artifact.headers.get('cache-control'), /immutable/);
  const emitted = await artifact.text(); assert.match(emitted, /packages\/ui\/1\.0\.0\/index.js/);
  assert.equal(server.hub.jobs('research').length, count);
  assert.equal((await fetch(server.hostOrigin + '/api/work', { method: 'POST' })).status, 403);
  const blocked = await fetch(server.assetOrigin + '/objects/research/' + publication.artifact + '/metadata.sqlite');
  assert.equal(blocked.status, 404);
  results.push({ check: 'reads serve immutable JS without builds; control writes require token', pass: true });
  fs.mkdirSync('artifacts/content-hub', { recursive: true });
  await page.screenshot({ path: 'artifacts/content-hub/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'artifacts/content-hub/phone.png', fullPage: true });
  assert.deepEqual(errors, []);
  results.push({ check: 'phone/desktop layout and sandboxed interactive rendering; no page errors', pass: true });
  const report = { results, errors, viewports: ['1280×1000', '390×844'] };
  fs.writeFileSync('artifacts/content-hub/browser.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally {
  await browser.close(); await server.close(); fs.rmSync(root, { recursive: true, force: true });
}
